CREATE OR REPLACE VIEW v_latest_stage_attempts AS
SELECT DISTINCT ON (run.build_id, run.stage_id)
    run.stage_run_id,
    run.build_id,
    run.stage_id,
    stage.stage_name,
    run.attempt_no,
    run.state,
    run.started_at,
    run.finished_at,
    run.error_message
FROM stage_runs run
JOIN pipeline_stages stage
  ON stage.stage_id = run.stage_id
ORDER BY
    run.build_id,
    run.stage_id,
    run.attempt_no DESC;


CREATE OR REPLACE VIEW v_build_overview AS
SELECT
    build.build_id,
    pipeline.pipeline_name,
    pipeline.kind,
    build.build_number,
    build.branch_name,
    build.commit_sha,
    build.state,
    build.triggered_by,
    build.created_at,
    build.started_at,
    build.finished_at,
    COUNT(latest.stage_run_id) AS recorded_stages,
    COUNT(*) FILTER (
        WHERE latest.state = 'success'
    ) AS successful_stages,
    COUNT(*) FILTER (
        WHERE latest.state = 'failed'
    ) AS failed_stages,
    COUNT(*) FILTER (
        WHERE latest.state = 'skipped'
    ) AS skipped_stages
FROM builds build
JOIN pipelines pipeline
  ON pipeline.pipeline_id = build.pipeline_id
LEFT JOIN v_latest_stage_attempts latest
  ON latest.build_id = build.build_id
GROUP BY
    build.build_id,
    pipeline.pipeline_name,
    pipeline.kind;

