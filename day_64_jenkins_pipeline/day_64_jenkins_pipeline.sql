    stage.stage_name,
    credential.credential_name,
    credential.credential_type,
    credential.scope_description,
    credential.last_rotated_at,
    credential.active
FROM credential_bindings binding
JOIN pipelines pipeline
  ON pipeline.pipeline_id = binding.pipeline_id
JOIN pipeline_stages stage
  ON stage.stage_id = binding.stage_id
JOIN credential_catalog credential
  ON credential.credential_id = binding.credential_id
ORDER BY pipeline.pipeline_name, stage.sequence_no;

-- ---------------------------------------------------------------------------
-- Workflow validation: incomplete required stages in running builds
-- ---------------------------------------------------------------------------

SELECT
    build.build_id,
    build.build_number,
    stage.stage_name,
    latest.state AS latest_stage_state
FROM builds build
JOIN pipeline_stages stage
  ON stage.pipeline_id = build.pipeline_id
LEFT JOIN LATERAL (
    SELECT run.state
    FROM stage_runs run
    WHERE run.build_id = build.build_id
      AND run.stage_id = stage.stage_id
    ORDER BY run.attempt_no DESC
    LIMIT 1
) latest ON TRUE
WHERE build.state = 'running'
  AND stage.required = TRUE
  AND (
      latest.state IS NULL
      OR latest.state IN ('queued', 'running')
  )
ORDER BY build.build_number, stage.sequence_no;
