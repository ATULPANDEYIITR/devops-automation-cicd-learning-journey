-- ---------------------------------------------------------------------------
-- Retrieval: pipeline definitions and ordered stage configuration
-- ---------------------------------------------------------------------------

SELECT
    pipeline.pipeline_name,
    pipeline.kind,
    stage.sequence_no,
    stage.stage_name,
    stage.agent_label,
    stage.max_retries,
    stage.timeout_seconds,
    stage.requires_approval
FROM pipelines pipeline
JOIN pipeline_stages stage
  ON stage.pipeline_id = pipeline.pipeline_id
ORDER BY pipeline.pipeline_name, stage.sequence_no;

-- ---------------------------------------------------------------------------
-- Retrieval: recent build activity
-- ---------------------------------------------------------------------------

SELECT
    pipeline_name,
    build_number,
    branch_name,
    state,
    created_at,
    started_at,
    finished_at
FROM v_build_overview
ORDER BY created_at DESC;

-- ---------------------------------------------------------------------------
-- Validation: discover offline agents that match a stage label
-- ---------------------------------------------------------------------------

SELECT
    stage.stage_name,
    stage.agent_label,
    agent.agent_name,
    agent.online
FROM pipeline_stages stage
LEFT JOIN agents agent
  ON stage.agent_label = ANY(agent.labels)
WHERE stage.pipeline_id = 1
ORDER BY stage.sequence_no, agent.agent_name;

-- ---------------------------------------------------------------------------
-- Validation: inspect unsuccessful stage attempts
-- ---------------------------------------------------------------------------

SELECT
    build.build_number,
    pipeline.pipeline_name,
    latest.stage_name,
    latest.attempt_no,
    latest.state,
    latest.error_message
FROM v_latest_stage_attempts latest
JOIN builds build
  ON build.build_id = latest.build_id
JOIN pipelines pipeline
  ON pipeline.pipeline_id = build.pipeline_id
WHERE latest.state IN ('failed', 'unstable', 'aborted')
ORDER BY build.created_at DESC, latest.stage_name;

-- ---------------------------------------------------------------------------
-- Aggregation: build success and failure counts by pipeline
-- ---------------------------------------------------------------------------

SELECT
    pipeline_name,
    COUNT(*) AS total_builds,
    COUNT(*) FILTER (WHERE state = 'success') AS successful_builds,
    COUNT(*) FILTER (WHERE state = 'failed') AS failed_builds,
    COUNT(*) FILTER (WHERE state = 'unstable') AS unstable_builds,
    ROUND(
        100.0 * COUNT(*) FILTER (WHERE state = 'success')
        / NULLIF(COUNT(*), 0),
        2
    ) AS success_percentage
FROM v_build_overview
GROUP BY pipeline_name
ORDER BY pipeline_name;

-- ---------------------------------------------------------------------------
-- Aggregation: stage failure distribution
-- ---------------------------------------------------------------------------

SELECT
    pipeline.pipeline_name,
    latest.stage_name,
    COUNT(*) FILTER (
        WHERE latest.state = 'failed'
    ) AS failed_attempts,
    COUNT(*) FILTER (
        WHERE latest.state = 'success'
    ) AS successful_attempts,
    COUNT(*) AS recorded_builds
FROM v_latest_stage_attempts latest
JOIN builds build
  ON build.build_id = latest.build_id
JOIN pipelines pipeline
  ON pipeline.pipeline_id = build.pipeline_id
GROUP BY pipeline.pipeline_name, latest.stage_name
ORDER BY failed_attempts DESC, pipeline.pipeline_name;

-- ---------------------------------------------------------------------------
-- Evaluation: current approval requests and reviewer decisions
-- ---------------------------------------------------------------------------

SELECT
    approval.approval_id,
    pipeline.pipeline_name,
    build.build_number,
    stage.stage_name,
    requester.username AS requested_by,
    reviewer.username AS reviewed_by,
    approval.state,
    approval.justification,
    approval.requested_at,
    approval.reviewed_at
FROM approval_requests approval
JOIN builds build
  ON build.build_id = approval.build_id
JOIN pipelines pipeline
  ON pipeline.pipeline_id = build.pipeline_id
JOIN stage_runs run
  ON run.stage_run_id = approval.stage_run_id
JOIN pipeline_stages stage
  ON stage.stage_id = run.stage_id
JOIN users requester
  ON requester.user_id = approval.requested_by
LEFT JOIN users reviewer
  ON reviewer.user_id = approval.reviewed_by
ORDER BY approval.requested_at DESC;

