-- ---------------------------------------------------------------------------
-- Reporting: average recorded step execution time by step name
-- ---------------------------------------------------------------------------

SELECT
    step.step_name,
    COUNT(*) AS executions,
    ROUND(AVG(step.duration_ms), 2) AS average_duration_ms,
    MAX(step.duration_ms) AS maximum_duration_ms
FROM step_runs step
WHERE step.duration_ms IS NOT NULL
GROUP BY step.step_name
ORDER BY average_duration_ms DESC;

-- ---------------------------------------------------------------------------
-- Workflow processing: stage dependency map
-- ---------------------------------------------------------------------------

SELECT
    pipeline.pipeline_name,
    current_stage.stage_name AS stage,
    dependency_stage.stage_name AS depends_on
FROM stage_dependencies dependency
JOIN pipeline_stages current_stage
  ON current_stage.stage_id = dependency.stage_id
JOIN pipeline_stages dependency_stage
  ON dependency_stage.stage_id =
     dependency.depends_on_stage_id
JOIN pipelines pipeline
  ON pipeline.pipeline_id = current_stage.pipeline_id
ORDER BY pipeline.pipeline_name, current_stage.sequence_no;

