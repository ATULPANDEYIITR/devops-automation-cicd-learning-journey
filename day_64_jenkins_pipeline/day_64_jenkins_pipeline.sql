CREATE OR REPLACE FUNCTION start_build(p_build_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE builds
    SET state = 'running'
    WHERE build_id = p_build_id
      AND state = 'queued';

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Build % does not exist or is not queued',
            p_build_id;
    END IF;

    INSERT INTO pipeline_events (
        build_id, actor, event_type, details
    )
    VALUES (
        p_build_id,
        'jenkins-controller',
        'BUILD_STARTED',
        jsonb_build_object('source', 'workflow-function')
    );
END;
$$;


CREATE OR REPLACE FUNCTION set_stage_state(
    p_stage_run_id BIGINT,
    p_new_state stage_state,
    p_error_message TEXT DEFAULT NULL
)
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE stage_runs
    SET state = p_new_state,
        error_message = p_error_message
    WHERE stage_run_id = p_stage_run_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Stage run % does not exist',
            p_stage_run_id;
    END IF;
END;
$$;


CREATE OR REPLACE FUNCTION finalize_build(p_build_id BIGINT)
RETURNS build_state
LANGUAGE plpgsql
AS $$
DECLARE
    selected_pipeline_id BIGINT;
    has_incomplete_required_stage BOOLEAN;
    has_required_failure BOOLEAN;
    has_degraded_stage BOOLEAN;
    final_state build_state;
BEGIN
    SELECT pipeline_id
    INTO selected_pipeline_id
    FROM builds
    WHERE build_id = p_build_id
      AND state = 'running';

    IF selected_pipeline_id IS NULL THEN
        RAISE EXCEPTION
            'Build % is not running or does not exist',
            p_build_id;
    END IF;

    SELECT
        COALESCE(
            BOOL_OR(
                stage.required
                AND (
                    latest.state IS NULL
                    OR latest.state IN ('queued', 'running')
                )
            ),
            FALSE
        ),
        COALESCE(
            BOOL_OR(
                stage.required
                AND latest.state IN ('failed', 'aborted')
            ),
            FALSE
        ),
        COALESCE(
            BOOL_OR(
                latest.state IN ('failed', 'unstable', 'aborted')
            ),
            FALSE
        )
    INTO
        has_incomplete_required_stage,
        has_required_failure,
        has_degraded_stage
    FROM pipeline_stages stage
    LEFT JOIN LATERAL (
        SELECT run.state
        FROM stage_runs run
        WHERE run.build_id = p_build_id
          AND run.stage_id = stage.stage_id
        ORDER BY run.attempt_no DESC
        LIMIT 1
    ) latest ON TRUE
    WHERE stage.pipeline_id = selected_pipeline_id;

    IF has_incomplete_required_stage THEN
        RAISE EXCEPTION
            'Build % has incomplete required stages',
            p_build_id;
    END IF;

    IF has_required_failure THEN
        final_state := 'failed';
    ELSIF has_degraded_stage THEN
        final_state := 'unstable';
    ELSE
        final_state := 'success';
    END IF;

    UPDATE builds
    SET state = final_state
    WHERE build_id = p_build_id;

    INSERT INTO pipeline_events (
        build_id, actor, event_type, details
    )
    VALUES (
        p_build_id,
        'jenkins-controller',
        'BUILD_FINALIZED',
        jsonb_build_object('state', final_state::TEXT)
    );

    RETURN final_state;
END;
$$;


CREATE OR REPLACE FUNCTION deployment_eligible(p_build_id BIGINT)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM builds build
        JOIN stage_runs deployment_run
          ON deployment_run.build_id = build.build_id
        JOIN pipeline_stages deployment_stage
          ON deployment_stage.stage_id = deployment_run.stage_id
        WHERE build.build_id = p_build_id
          AND build.state = 'running'
          AND deployment_stage.requires_approval = TRUE
          AND deployment_run.state = 'queued'
          AND deployment_run.attempt_no = (
              SELECT MAX(latest.attempt_no)
              FROM stage_runs latest
              WHERE latest.build_id = deployment_run.build_id
                AND latest.stage_id = deployment_run.stage_id
          )
          AND EXISTS (
              SELECT 1
              FROM approval_requests approval
              WHERE approval.stage_run_id =
                    deployment_run.stage_run_id
                AND approval.state = 'approved'
          )
          AND NOT EXISTS (
              SELECT 1
              FROM stage_dependencies dependency
              WHERE dependency.stage_id =
                    deployment_stage.stage_id
                AND NOT EXISTS (
                    SELECT 1
                    FROM stage_runs dependency_run
                    WHERE dependency_run.build_id = build.build_id
                      AND dependency_run.stage_id =
                          dependency.depends_on_stage_id
                      AND dependency_run.attempt_no = (
                          SELECT MAX(latest.attempt_no)
                          FROM stage_runs latest
                          WHERE latest.build_id = build.build_id
                            AND latest.stage_id =
                                dependency.depends_on_stage_id
                      )
                      AND dependency_run.state = 'success'
                )
          )
    );
$$;

