-- Jenkins Pipeline relational workflow model.
-- The schema stores pipeline definitions, builds, stages, agents,
-- execution attempts, artifacts, credentials metadata and approvals.
--
-- Credential secret material is deliberately not stored in this database.
-- This script resets the learning schema before creating sample data.

DROP SCHEMA IF EXISTS jenkins_lab CASCADE;
CREATE SCHEMA jenkins_lab;
SET search_path TO jenkins_lab, public;

CREATE TYPE pipeline_kind AS ENUM (
    'declarative',
    'scripted'
);

CREATE TYPE build_state AS ENUM (
    'queued',
    'running',
    'success',
    'failed',
    'unstable',
    'aborted'
);

CREATE TYPE stage_state AS ENUM (
    'queued',
    'running',
    'success',
    'failed',
    'skipped',
    'unstable',
    'aborted'
);

CREATE TYPE approval_state AS ENUM (
    'pending',
    'approved',
    'rejected',
    'cancelled'
);

CREATE TYPE step_state AS ENUM (
    'running',
    'success',
    'failed',
    'skipped'
);

-- ---------------------------------------------------------------------------
-- Identity and execution infrastructure
-- ---------------------------------------------------------------------------

CREATE TABLE users (
    user_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         TEXT NOT NULL UNIQUE,
    display_name     TEXT NOT NULL,
    active           BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE agents (
    agent_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_name       TEXT NOT NULL UNIQUE,
    labels           TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    online           BOOLEAN NOT NULL DEFAULT TRUE,
    executor_count   INTEGER NOT NULL DEFAULT 1
                     CHECK (executor_count > 0),
    last_seen_at     TIMESTAMPTZ
);

CREATE TABLE pipelines (
    pipeline_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_name    TEXT NOT NULL UNIQUE,
    kind             pipeline_kind NOT NULL,
    repository_url   TEXT NOT NULL
                     CHECK (repository_url ~ '^https://'),
    default_branch   TEXT NOT NULL DEFAULT 'main',
    enabled          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE pipeline_stages (
    stage_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_id          BIGINT NOT NULL
                         REFERENCES pipelines(pipeline_id)
                         ON DELETE CASCADE,
    stage_name           TEXT NOT NULL,
    sequence_no          INTEGER NOT NULL CHECK (sequence_no > 0),
    agent_label          TEXT NOT NULL,
    max_retries          INTEGER NOT NULL DEFAULT 0
                         CHECK (max_retries >= 0),
    timeout_seconds      INTEGER NOT NULL DEFAULT 900
                         CHECK (timeout_seconds > 0),
    required             BOOLEAN NOT NULL DEFAULT TRUE,
    requires_approval    BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (pipeline_id, stage_name),
    UNIQUE (pipeline_id, sequence_no)
);

CREATE TABLE stage_dependencies (
    stage_id             BIGINT NOT NULL
                         REFERENCES pipeline_stages(stage_id)
                         ON DELETE CASCADE,
    depends_on_stage_id  BIGINT NOT NULL
                         REFERENCES pipeline_stages(stage_id)
                         ON DELETE CASCADE,
    PRIMARY KEY (stage_id, depends_on_stage_id),
    CHECK (stage_id <> depends_on_stage_id)
);

-- Credential catalog entries identify references and scopes only.
-- Actual passwords, tokens and private keys belong in Jenkins credentials.
CREATE TABLE credential_catalog (
    credential_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credential_name   TEXT NOT NULL UNIQUE,
    credential_type   TEXT NOT NULL
                      CHECK (credential_type IN (
                          'secret_text',
                          'username_password',
                          'ssh_private_key',
                          'certificate'
                      )),
    scope_description TEXT NOT NULL,
    last_rotated_at   TIMESTAMPTZ,
    active            BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE credential_bindings (
    binding_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_id       BIGINT NOT NULL
                      REFERENCES pipelines(pipeline_id)
                      ON DELETE CASCADE,
    stage_id          BIGINT NOT NULL
                      REFERENCES pipeline_stages(stage_id)
                      ON DELETE CASCADE,
    credential_id     BIGINT NOT NULL
                      REFERENCES credential_catalog(credential_id),
    variable_name     TEXT NOT NULL,
    UNIQUE (stage_id, credential_id),
    UNIQUE (stage_id, variable_name)
);

-- ---------------------------------------------------------------------------
-- Build and execution records
-- ---------------------------------------------------------------------------

CREATE TABLE builds (
    build_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_id       BIGINT NOT NULL
                      REFERENCES pipelines(pipeline_id),
    build_number      INTEGER NOT NULL CHECK (build_number > 0),
    branch_name       TEXT NOT NULL,
    commit_sha        TEXT NOT NULL
                      CHECK (commit_sha ~ '^[0-9a-fA-F]{40,64}$'),
    triggered_by      BIGINT NOT NULL REFERENCES users(user_id),
    state             build_state NOT NULL DEFAULT 'queued',
    parameters        JSONB NOT NULL DEFAULT '{}'::JSONB
                      CHECK (jsonb_typeof(parameters) = 'object'),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at        TIMESTAMPTZ,
    finished_at       TIMESTAMPTZ,
    UNIQUE (pipeline_id, build_number),
    CHECK (
        finished_at IS NULL
        OR started_at IS NOT NULL
    ),
    CHECK (
        state NOT IN ('success', 'failed', 'unstable', 'aborted')
        OR finished_at IS NOT NULL
    )
);

CREATE TABLE stage_runs (
    stage_run_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    build_id          BIGINT NOT NULL
                      REFERENCES builds(build_id)
                      ON DELETE CASCADE,
    stage_id          BIGINT NOT NULL
                      REFERENCES pipeline_stages(stage_id),
    attempt_no        INTEGER NOT NULL CHECK (attempt_no > 0),
    state             stage_state NOT NULL DEFAULT 'queued',
    started_at        TIMESTAMPTZ,
    finished_at       TIMESTAMPTZ,
    error_message     TEXT,
    UNIQUE (build_id, stage_id, attempt_no),
    CHECK (
        finished_at IS NULL
        OR started_at IS NOT NULL
        OR state IN ('skipped', 'aborted')
    )
);

CREATE TABLE step_runs (
    step_run_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_run_id      BIGINT NOT NULL
                      REFERENCES stage_runs(stage_run_id)
                      ON DELETE CASCADE,
    sequence_no       INTEGER NOT NULL CHECK (sequence_no > 0),
    step_name         TEXT NOT NULL,
    state             step_state NOT NULL,
    started_at        TIMESTAMPTZ,
    finished_at       TIMESTAMPTZ,
    duration_ms       BIGINT CHECK (duration_ms IS NULL OR duration_ms >= 0),
    log_excerpt       TEXT,
    UNIQUE (stage_run_id, sequence_no),
    CHECK (
        finished_at IS NULL
        OR started_at IS NOT NULL
    )
);

CREATE TABLE artifacts (
    artifact_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    build_id          BIGINT NOT NULL
                      REFERENCES builds(build_id)
                      ON DELETE CASCADE,
    stage_run_id      BIGINT
                      REFERENCES stage_runs(stage_run_id),
    artifact_name     TEXT NOT NULL,
    checksum_sha256   TEXT NOT NULL
                      CHECK (checksum_sha256 ~ '^[0-9a-fA-F]{64}$'),
    storage_uri       TEXT NOT NULL
                      CHECK (storage_uri ~ '^https://'),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (build_id, artifact_name)
);

CREATE TABLE approval_requests (
    approval_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    build_id          BIGINT NOT NULL
                      REFERENCES builds(build_id)
                      ON DELETE CASCADE,
    stage_run_id      BIGINT NOT NULL
                      REFERENCES stage_runs(stage_run_id)
                      ON DELETE CASCADE,
    requested_by      BIGINT NOT NULL REFERENCES users(user_id),
    reviewed_by       BIGINT REFERENCES users(user_id),
    state             approval_state NOT NULL DEFAULT 'pending',
    justification     TEXT,
    requested_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at       TIMESTAMPTZ,
    UNIQUE (stage_run_id),
    CHECK (
        state = 'pending'
        OR (
            reviewed_by IS NOT NULL
            AND reviewed_at IS NOT NULL
        )
    )
);

CREATE TABLE pipeline_events (
    event_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    build_id          BIGINT NOT NULL
                      REFERENCES builds(build_id)
                      ON DELETE CASCADE,
    actor             TEXT NOT NULL,
    event_type        TEXT NOT NULL,
    details           JSONB NOT NULL DEFAULT '{}'::JSONB
                      CHECK (jsonb_typeof(details) = 'object'),
    occurred_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

