-- ---------------------------------------------------------------------------
-- Build state transition enforcement
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION enforce_build_state_transition()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.state IS DISTINCT FROM OLD.state THEN
        IF NOT (
            (OLD.state = 'queued'
                AND NEW.state IN ('running', 'aborted'))
            OR
            (OLD.state = 'running'
                AND NEW.state IN (
                    'success', 'failed', 'unstable', 'aborted'
                ))
        ) THEN
            RAISE EXCEPTION
                'Invalid build transition: % -> %',
                OLD.state, NEW.state;
        END IF;

        IF NEW.state = 'running' THEN
            NEW.started_at := COALESCE(
                NEW.started_at,
                CURRENT_TIMESTAMP
            );
        ELSE
            NEW.finished_at := COALESCE(
                NEW.finished_at,
                CURRENT_TIMESTAMP
            );
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_build_state_transition
BEFORE UPDATE OF state ON builds
FOR EACH ROW
EXECUTE FUNCTION enforce_build_state_transition();

-- ---------------------------------------------------------------------------
-- Stage-run integrity and transition enforcement
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION validate_stage_run_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    build_pipeline_id BIGINT;
    stage_pipeline_id BIGINT;
BEGIN
    SELECT pipeline_id
    INTO build_pipeline_id
    FROM builds
    WHERE build_id = NEW.build_id;

    SELECT pipeline_id
    INTO stage_pipeline_id
    FROM pipeline_stages
    WHERE stage_id = NEW.stage_id;

    IF build_pipeline_id IS NULL
       OR stage_pipeline_id IS NULL
       OR build_pipeline_id <> stage_pipeline_id THEN
        RAISE EXCEPTION
            'Stage and build must belong to the same pipeline';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_stage_run_insert
BEFORE INSERT ON stage_runs
FOR EACH ROW
EXECUTE FUNCTION validate_stage_run_insert();


CREATE OR REPLACE FUNCTION enforce_stage_run_transition()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    parent_build_state build_state;
    stage_needs_approval BOOLEAN;
    dependency_count INTEGER;
    satisfied_count INTEGER;
BEGIN
    IF NEW.state IS NOT DISTINCT FROM OLD.state THEN
        RETURN NEW;
    END IF;

    IF NOT (
        (OLD.state = 'queued'
            AND NEW.state IN ('running', 'skipped', 'aborted'))
        OR
        (OLD.state = 'running'
            AND NEW.state IN (
                'success', 'failed', 'unstable', 'aborted'
            ))
    ) THEN
        RAISE EXCEPTION
            'Invalid stage transition: % -> %',
            OLD.state, NEW.state;
    END IF;

    IF NEW.state = 'running' AND OLD.state = 'queued' THEN
        SELECT state
        INTO parent_build_state
        FROM builds
        WHERE build_id = NEW.build_id;

        IF parent_build_state <> 'running' THEN
            RAISE EXCEPTION
                'A stage can run only while its build is running';
        END IF;

        SELECT requires_approval
        INTO stage_needs_approval
        FROM pipeline_stages
        WHERE stage_id = NEW.stage_id;

        SELECT COUNT(*)
        INTO dependency_count
        FROM stage_dependencies
        WHERE stage_id = NEW.stage_id;

        SELECT COUNT(*)
        INTO satisfied_count
        FROM stage_dependencies dependency
        WHERE dependency.stage_id = NEW.stage_id
          AND EXISTS (
              SELECT 1
              FROM stage_runs dependency_run
              WHERE dependency_run.build_id = NEW.build_id
                AND dependency_run.stage_id =
                    dependency.depends_on_stage_id
                AND dependency_run.attempt_no = (
                    SELECT MAX(latest.attempt_no)
                    FROM stage_runs latest
                    WHERE latest.build_id = NEW.build_id
                      AND latest.stage_id =
                          dependency.depends_on_stage_id
                )
                AND dependency_run.state = 'success'
          );

        IF dependency_count <> satisfied_count THEN
            RAISE EXCEPTION
                'Stage % cannot start before all dependencies succeed',
                NEW.stage_id;
        END IF;

        IF stage_needs_approval
           AND NOT EXISTS (
               SELECT 1
               FROM approval_requests approval
               WHERE approval.stage_run_id = NEW.stage_run_id
                 AND approval.state = 'approved'
           ) THEN
            RAISE EXCEPTION
                'Stage % requires an approved request',
                NEW.stage_id;
        END IF;

        NEW.started_at := COALESCE(
            NEW.started_at,
            CURRENT_TIMESTAMP
        );
        NEW.finished_at := NULL;
    ELSE
        NEW.finished_at := COALESCE(
            NEW.finished_at,
            CURRENT_TIMESTAMP
        );
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_stage_run_transition
BEFORE UPDATE OF state ON stage_runs
FOR EACH ROW
EXECUTE FUNCTION enforce_stage_run_transition();

-- ---------------------------------------------------------------------------
-- Approval workflow enforcement
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION enforce_approval_workflow()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    stage_requires_approval BOOLEAN;
    stage_build_id BIGINT;
    reviewer_is_active BOOLEAN;
BEGIN
    IF TG_OP = 'INSERT' THEN
        SELECT run.build_id, stage.requires_approval
        INTO stage_build_id, stage_requires_approval
        FROM stage_runs run
        JOIN pipeline_stages stage
          ON stage.stage_id = run.stage_id
        WHERE run.stage_run_id = NEW.stage_run_id;

        IF stage_build_id IS NULL
           OR stage_build_id <> NEW.build_id THEN
            RAISE EXCEPTION
                'Approval request must reference its stage run build';
        END IF;

        IF NOT stage_requires_approval THEN
            RAISE EXCEPTION
                'Approval requested for a stage that does not require it';
        END IF;
    ELSE
        IF OLD.state <> 'pending'
           OR NEW.state NOT IN (
               'approved', 'rejected', 'cancelled'
           ) THEN
            RAISE EXCEPTION
                'Approval can only move from pending to a final state';
        END IF;

        IF NEW.state IN ('approved', 'rejected') THEN
            IF NEW.reviewed_by IS NULL THEN
                RAISE EXCEPTION
                    'A reviewer is required for a decision';
            END IF;

            IF NEW.reviewed_by = NEW.requested_by THEN
                RAISE EXCEPTION
                    'Requester cannot approve their own deployment';
            END IF;

            SELECT active
            INTO reviewer_is_active
            FROM users
            WHERE user_id = NEW.reviewed_by;

            IF reviewer_is_active IS DISTINCT FROM TRUE THEN
                RAISE EXCEPTION
                    'Reviewer must be an active user';
            END IF;
        END IF;

        NEW.reviewed_at := CURRENT_TIMESTAMP;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_approval_workflow
BEFORE INSERT OR UPDATE OF state ON approval_requests
FOR EACH ROW
EXECUTE FUNCTION enforce_approval_workflow();

