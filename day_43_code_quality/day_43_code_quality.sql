-- Code Quality Governance: PostgreSQL 15+
--
-- Models the relationship between proposed changes, review decisions,
-- approval eligibility, automated quality checks, and protected branches.
--
-- Run in a dedicated development database:
--   psql -v ON_ERROR_STOP=1 -f code_quality_governance.sql
--
-- The final queries show merge eligibility. The schema does not claim to
-- replace server-side enforcement by GitHub, GitLab, or another Git host.

BEGIN;

CREATE SCHEMA IF NOT EXISTS code_quality;

SET search_path TO code_quality, public;

CREATE TABLE IF NOT EXISTS repositories (
    repository_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_name TEXT NOT NULL,
    repository_name TEXT NOT NULL,
    default_branch TEXT NOT NULL DEFAULT 'main',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT repository_owner_nonempty CHECK (btrim(owner_name) <> ''),
    CONSTRAINT repository_name_nonempty CHECK (btrim(repository_name) <> ''),
    CONSTRAINT repository_branch_nonempty CHECK (btrim(default_branch) <> ''),
    CONSTRAINT repository_name_unique UNIQUE (owner_name, repository_name)
);

CREATE TABLE IF NOT EXISTS repository_members (
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    username TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    can_review_code BOOLEAN NOT NULL DEFAULT FALSE,
    is_bot BOOLEAN NOT NULL DEFAULT FALSE,
    is_administrator BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (repository_id, username),
    CONSTRAINT member_username_nonempty CHECK (btrim(username) <> '')
);

CREATE TABLE IF NOT EXISTS branches (
    branch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    branch_name TEXT NOT NULL,
    head_sha TEXT NOT NULL,
    protected BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT branch_name_nonempty CHECK (btrim(branch_name) <> ''),
    CONSTRAINT branch_sha_nonempty CHECK (btrim(head_sha) <> ''),
    CONSTRAINT branch_unique UNIQUE (repository_id, branch_name)
);

CREATE TABLE IF NOT EXISTS branch_protection_policies (
    policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL UNIQUE REFERENCES branches(branch_id)
        ON DELETE CASCADE,
    required_approvals INTEGER NOT NULL DEFAULT 1,
    require_lint BOOLEAN NOT NULL DEFAULT TRUE,
    require_format BOOLEAN NOT NULL DEFAULT TRUE,
    require_static_analysis BOOLEAN NOT NULL DEFAULT TRUE,
    require_tests BOOLEAN NOT NULL DEFAULT TRUE,
    require_up_to_date BOOLEAN NOT NULL DEFAULT TRUE,
    require_resolved_conversations BOOLEAN NOT NULL DEFAULT TRUE,
    require_linear_history BOOLEAN NOT NULL DEFAULT FALSE,
    allow_direct_pushes BOOLEAN NOT NULL DEFAULT FALSE,
    allow_force_pushes BOOLEAN NOT NULL DEFAULT FALSE,
    allow_deletion BOOLEAN NOT NULL DEFAULT FALSE,
    allow_administrator_bypass BOOLEAN NOT NULL DEFAULT FALSE,
    dismiss_stale_approvals BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT approval_count_nonnegative CHECK (required_approvals >= 0)
);

CREATE TABLE IF NOT EXISTS pull_requests (
    pull_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id)
        ON DELETE CASCADE,
    number INTEGER NOT NULL,
    author TEXT NOT NULL,
    base_branch_id BIGINT NOT NULL REFERENCES branches(branch_id),
    head_branch TEXT NOT NULL,
    head_sha TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'open',
    is_draft BOOLEAN NOT NULL DEFAULT FALSE,
    branch_up_to_date BOOLEAN NOT NULL DEFAULT FALSE,
    has_merge_conflicts BOOLEAN NOT NULL DEFAULT FALSE,
    merge_method TEXT,
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    merged_at TIMESTAMPTZ,
    CONSTRAINT pr_number_positive CHECK (number > 0),
    CONSTRAINT pr_author_nonempty CHECK (btrim(author) <> ''),
    CONSTRAINT pr_head_branch_nonempty CHECK (btrim(head_branch) <> ''),
    CONSTRAINT pr_head_sha_nonempty CHECK (btrim(head_sha) <> ''),
    CONSTRAINT pr_state_valid CHECK (state IN ('open', 'closed', 'merged')),
    CONSTRAINT pr_merge_method_valid CHECK (
        merge_method IS NULL OR
        merge_method IN ('merge_commit', 'squash', 'rebase')
    ),
    CONSTRAINT pr_number_unique UNIQUE (repository_id, number)
);

CREATE TABLE IF NOT EXISTS commits (
    commit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id BIGINT NOT NULL REFERENCES pull_requests(pull_request_id)
        ON DELETE CASCADE,
    commit_sha TEXT NOT NULL,
    parent_sha TEXT,
    author TEXT NOT NULL,
    commit_message TEXT NOT NULL,
    committed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT commit_sha_nonempty CHECK (btrim(commit_sha) <> ''),
    CONSTRAINT commit_author_nonempty CHECK (btrim(author) <> ''),
    CONSTRAINT commit_message_nonempty CHECK (btrim(commit_message) <> ''),
    CONSTRAINT pr_commit_unique UNIQUE (pull_request_id, commit_sha)
);

CREATE TABLE IF NOT EXISTS changed_files (
    changed_file_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commit_id BIGINT NOT NULL REFERENCES commits(commit_id)
        ON DELETE CASCADE,
    file_path TEXT NOT NULL,
    change_type TEXT NOT NULL,
    additions INTEGER NOT NULL DEFAULT 0,
    deletions INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT changed_file_path_nonempty CHECK (btrim(file_path) <> ''),
    CONSTRAINT changed_file_type_valid CHECK (
        change_type IN ('added', 'modified', 'deleted', 'renamed')
    ),
    CONSTRAINT changed_file_counts_nonnegative CHECK (
        additions >= 0 AND deletions >= 0
    ),
    CONSTRAINT commit_file_unique UNIQUE (commit_id, file_path)
);

CREATE TABLE IF NOT EXISTS reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id BIGINT NOT NULL REFERENCES pull_requests(pull_request_id)
        ON DELETE CASCADE,
    reviewer TEXT NOT NULL,
    state TEXT NOT NULL,
    reviewed_sha TEXT NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    review_body TEXT NOT NULL DEFAULT '',
    CONSTRAINT review_state_valid CHECK (
        state IN ('pending', 'approved', 'changes_requested', 'dismissed')
    ),
    CONSTRAINT review_reviewer_nonempty CHECK (btrim(reviewer) <> ''),
    CONSTRAINT review_sha_nonempty CHECK (btrim(reviewed_sha) <> '')
);

CREATE TABLE IF NOT EXISTS review_comments (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL REFERENCES reviews(review_id)
        ON DELETE CASCADE,
    file_path TEXT NOT NULL,
    line_number INTEGER,
    side TEXT NOT NULL DEFAULT 'right',
    body TEXT NOT NULL,
    resolved BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ,
    CONSTRAINT comment_line_positive CHECK (
        line_number IS NULL OR line_number > 0
    ),
    CONSTRAINT comment_side_valid CHECK (side IN ('left', 'right')),
    CONSTRAINT comment_body_nonempty CHECK (btrim(body) <> ''),
    CONSTRAINT comment_resolution_consistent CHECK (
        (resolved = FALSE AND resolved_at IS NULL)
        OR (resolved = TRUE AND resolved_at IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS status_checks (
    status_check_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id BIGINT NOT NULL REFERENCES pull_requests(pull_request_id)
        ON DELETE CASCADE,
    check_name TEXT NOT NULL,
    commit_sha TEXT NOT NULL,
    status TEXT NOT NULL,
    details TEXT NOT NULL DEFAULT '',
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    CONSTRAINT check_name_nonempty CHECK (btrim(check_name) <> ''),
    CONSTRAINT check_sha_nonempty CHECK (btrim(commit_sha) <> ''),
    CONSTRAINT check_status_valid CHECK (
        status IN ('pending', 'passed', 'failed', 'cancelled')
    ),
    CONSTRAINT check_completion_consistent CHECK (
        (status = 'pending' AND completed_at IS NULL)
        OR (status <> 'pending' AND completed_at IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_pr_repository_state
    ON pull_requests(repository_id, state);

CREATE INDEX IF NOT EXISTS idx_reviews_pr_state
    ON reviews(pull_request_id, state);

CREATE INDEX IF NOT EXISTS idx_reviews_reviewer_time
    ON reviews(reviewer, submitted_at DESC);

CREATE INDEX IF NOT EXISTS idx_comments_unresolved
    ON review_comments(review_id)
    WHERE resolved = FALSE;

CREATE INDEX IF NOT EXISTS idx_status_checks_pr_name
    ON status_checks(pull_request_id, check_name, started_at DESC);

CREATE INDEX IF NOT EXISTS idx_commits_pr_time
    ON commits(pull_request_id, committed_at DESC);

