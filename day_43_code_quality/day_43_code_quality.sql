-- A view separates raw review records from currently valid approvals.
-- It excludes authors, inactive users, bots, unauthorized reviewers, and
-- approvals attached to an obsolete source commit.
CREATE OR REPLACE VIEW current_valid_approvals AS
SELECT
    pr.pull_request_id,
    r.reviewer,
    r.reviewed_sha,
    r.submitted_at
FROM pull_requests AS pr
JOIN reviews AS r
    ON r.pull_request_id = pr.pull_request_id
JOIN repository_members AS member
    ON member.repository_id = pr.repository_id
   AND member.username = r.reviewer
JOIN branch_protection_policies AS policy
    ON policy.branch_id = pr.base_branch_id
WHERE r.state = 'approved'
  AND member.active
  AND member.can_review_code
  AND NOT member.is_bot
  AND r.reviewer <> pr.author
  AND (
      NOT policy.dismiss_stale_approvals
      OR r.reviewed_sha = pr.head_sha
  );

-- A CTE computes the latest result for each required check name and
-- pull request. A passing result for an older commit does not satisfy the
-- current source revision.
CREATE OR REPLACE VIEW pull_request_quality_status AS
WITH latest_checks AS (
    SELECT DISTINCT ON (sc.pull_request_id, sc.check_name)
        sc.pull_request_id,
        sc.check_name,
        sc.commit_sha,
        sc.status,
        sc.completed_at
    FROM status_checks AS sc
    ORDER BY
        sc.pull_request_id,
        sc.check_name,
        sc.started_at DESC,
        sc.status_check_id DESC
),
approval_counts AS (
    SELECT
        pr.pull_request_id,
        COUNT(DISTINCT approval.reviewer) AS valid_approvals
    FROM pull_requests AS pr
    LEFT JOIN current_valid_approvals AS approval
        ON approval.pull_request_id = pr.pull_request_id
    GROUP BY pr.pull_request_id
),
conversation_counts AS (
    SELECT
        pr.pull_request_id,
        COUNT(comment.comment_id) FILTER (
            WHERE comment.resolved = FALSE
        ) AS unresolved_comments
    FROM pull_requests AS pr
    LEFT JOIN reviews AS r
        ON r.pull_request_id = pr.pull_request_id
    LEFT JOIN review_comments AS comment
        ON comment.review_id = r.review_id
    GROUP BY pr.pull_request_id
),
check_counts AS (
    SELECT
        pr.pull_request_id,
        COUNT(DISTINCT required.check_name) FILTER (
            WHERE check_result.status = 'passed'
              AND check_result.commit_sha = pr.head_sha
        ) AS passing_required_checks,
        COUNT(DISTINCT required.check_name) AS total_required_checks
    FROM pull_requests AS pr
    JOIN branch_protection_policies AS policy
        ON policy.branch_id = pr.base_branch_id
    CROSS JOIN LATERAL (
        VALUES
            ('lint', policy.require_lint),
            ('format', policy.require_format),
            ('static-analysis', policy.require_static_analysis),
            ('tests', policy.require_tests)
    ) AS required(check_name, is_required)
    LEFT JOIN latest_checks AS check_result
        ON check_result.pull_request_id = pr.pull_request_id
       AND check_result.check_name = required.check_name
    WHERE required.is_required
    GROUP BY pr.pull_request_id
)
SELECT
    pr.pull_request_id,
    repo.owner_name,
    repo.repository_name,
    pr.number,
    pr.author,
    pr.base_branch_id,
    base.branch_name AS base_branch,
    pr.head_branch,
    pr.head_sha,
    pr.state,
    pr.is_draft,
    pr.branch_up_to_date,
    pr.has_merge_conflicts,
    policy.required_approvals,
    COALESCE(approval_counts.valid_approvals, 0) AS valid_approvals,
    COALESCE(conversation_counts.unresolved_comments, 0)
        AS unresolved_comments,
    COALESCE(check_counts.passing_required_checks, 0)
        AS passing_required_checks,
    COALESCE(check_counts.total_required_checks, 0)
        AS total_required_checks,
    policy.require_up_to_date,
    policy.require_resolved_conversations,
    policy.require_linear_history
FROM pull_requests AS pr
JOIN repositories AS repo
    ON repo.repository_id = pr.repository_id
JOIN branches AS base
    ON base.branch_id = pr.base_branch_id
JOIN branch_protection_policies AS policy
    ON policy.branch_id = pr.base_branch_id
LEFT JOIN approval_counts
    ON approval_counts.pull_request_id = pr.pull_request_id
LEFT JOIN conversation_counts
    ON conversation_counts.pull_request_id = pr.pull_request_id
LEFT JOIN check_counts
    ON check_counts.pull_request_id = pr.pull_request_id;

-- The following query reports all blockers rather than stopping at the first.
WITH evaluated AS (
    SELECT
        status.*,
        ARRAY_REMOVE(ARRAY[
            CASE WHEN status.state <> 'open'
                THEN 'Pull request is not open' END,
            CASE WHEN status.is_draft
                THEN 'Pull request is a draft' END,
            CASE WHEN status.has_merge_conflicts
                THEN 'Merge conflicts exist' END,
            CASE WHEN status.require_up_to_date
                      AND NOT status.branch_up_to_date
                THEN 'Source branch is not up to date' END,
            CASE WHEN status.require_resolved_conversations
                      AND status.unresolved_comments > 0
                THEN 'Review comments remain unresolved' END,
            CASE WHEN status.valid_approvals < status.required_approvals
                THEN 'Required approval count not met' END,
            CASE WHEN status.passing_required_checks
                      < status.total_required_checks
                THEN 'Required quality checks are not all passing' END,
            CASE WHEN status.require_linear_history
                      AND status.head_branch = status.base_branch
                THEN 'Source and target branches are identical' END
        ]::TEXT[], NULL) AS blockers
    FROM pull_request_quality_status AS status
)
SELECT
    number,
    head_branch,
    head_sha,
    valid_approvals,
    required_approvals,
    passing_required_checks,
    total_required_checks,
    blockers,
    cardinality(blockers) = 0 AS quality_gate_eligible
FROM evaluated
ORDER BY number;

-- Inspect review findings and unresolved inline discussions.
SELECT
    pr.number,
    r.reviewer,
    r.state AS review_state,
    comment.file_path,
    comment.line_number,
    comment.body,
    comment.resolved
FROM pull_requests AS pr
JOIN reviews AS r
    ON r.pull_request_id = pr.pull_request_id
JOIN review_comments AS comment
    ON comment.review_id = r.review_id
WHERE comment.resolved = FALSE
ORDER BY pr.number, comment.file_path, comment.line_number;

-- Branch-protection settings are repository governance, not review comments.
SELECT
    repo.owner_name,
    repo.repository_name,
    branch.branch_name,
    branch.protected,
    policy.required_approvals,
    policy.require_lint,
    policy.require_format,
    policy.require_static_analysis,
    policy.require_tests,
    policy.require_up_to_date,
    policy.require_resolved_conversations,
    policy.require_linear_history,
    policy.allow_direct_pushes,
    policy.allow_force_pushes,
    policy.allow_deletion,
    policy.allow_administrator_bypass,
    policy.dismiss_stale_approvals
FROM branches AS branch
JOIN repositories AS repo
    ON repo.repository_id = branch.repository_id
JOIN branch_protection_policies AS policy
    ON policy.branch_id = branch.branch_id
ORDER BY repo.repository_name, branch.branch_name;

