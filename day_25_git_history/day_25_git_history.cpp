static void runValidation(
    const fs::path& repository
) {
    section("12. Validation and operational checks");

    const auto headResult = gitCommand(
        repository,
        {"rev-parse", "HEAD"},
        false
    );

    const bool headExists =
        headResult.exitCode == 0 &&
        !headResult.output.empty();

    const int commitCount = std::stoi(
        gitText(
            repository,
            {"rev-list", "--count", "HEAD"}
        )
    );

    const auto parentResult = gitCommand(
        repository,
        {"rev-parse", "HEAD~1"},
        false
    );

    const auto showResult = gitCommand(
        repository,
        {"show", "--quiet", "HEAD"},
        false
    );

    const std::string status =
        gitText(repository, {"status", "--porcelain"});

    const bool clean = status.empty();

    const std::vector<std::pair<std::string, bool>> checks{
        {"HEAD resolves", headExists},
        {"At least three commits exist", commitCount >= 3},
        {"HEAD~1 resolves", parentResult.exitCode == 0},
        {"git show can inspect HEAD", showResult.exitCode == 0},
        {"Working tree is clean", clean}
    };

    bool allPassed = true;

    for (const auto& [description, passed] : checks) {
        std::cout
            << "["
            << (passed ? "PASS" : "FAIL")
            << "] "
            << description
            << "\n";

        allPassed = allPassed && passed;
    }

    if (!allPassed) {
        throw GitError("One or more validation checks failed.");
    }
}

static void demonstrateDiagnostic(
    const fs::path& repository
) {
    section("13. Repository diagnostic");

    const std::string branch =
        gitText(repository, {"branch", "--show-current"});

    const std::string head =
        shortHash(repository);

    const auto upstream = gitCommand(
        repository,
        {
            "rev-parse",
            "--abbrev-ref",
            "--symbolic-full-name",
            "@{u}"
        },
        false
    );

    std::cout << "Branch: " << branch << "\n";
    std::cout << "HEAD:   " << head << "\n";

    if (upstream.exitCode == 0) {
        std::cout
            << "Upstream: "
            << upstream.output;
    } else {
        std::cout << "Upstream: not configured\n";
    }

    std::cout << "\nStatus:\n";
    showStatus(repository);

    std::cout << "\nRecent history:\n";
    std::cout
        << gitText(
               repository,
               {"log", "--decorate", "--oneline", "-6"}
           )
        << "\n";

    std::cout << "\nUnstaged diff statistics:\n";
    const std::string unstaged =
        gitText(repository, {"diff", "--stat"});

    std::cout
        << (unstaged.empty() ? "(none)" : unstaged)
        << "\n";

    std::cout << "\nStaged diff statistics:\n";
    const std::string staged =
        gitText(
            repository,
            {"diff", "--cached", "--stat"}
        );

    std::cout
        << (staged.empty() ? "(none)" : staged)
        << "\n";
}

int main() {
    try {
        /*
         * Create a unique temporary directory. The demonstration never
         * operates on an existing user repository.
         */
        const fs::path temporaryDirectory =
            fs::temp_directory_path() /
            fs::path("git_history_cpp_learning");

        /*
         * A previous failed run should not contaminate the current
         * demonstration.
         */
        std::error_code cleanupError;
        fs::remove_all(temporaryDirectory, cleanupError);
        fs::create_directories(temporaryDirectory);

        /*
         * Confirm Git is installed.
         */
        const auto gitVersion =
            runShellCommand("git --version", temporaryDirectory);

        if (gitVersion.exitCode != 0) {
            throw GitError(
                "Git is not available on PATH.\n" +
                gitVersion.output
            );
        }

        std::cout
            << "Using "
            << gitVersion.output
            << "\n";

        explainRepositoryModel();

        const fs::path repository =
            createRepository(temporaryDirectory);

        std::cout
            << "\nTemporary repository: "
            << repository
            << "\n";

        demonstrateLog(repository);
        demonstrateShow(repository);
        demonstrateDiff(repository);
        demonstrateReset(repository);
        demonstrateRevert(repository);
        demonstrateRevisionExpressions(repository);
        demonstrateMergeHistory(repository);
        demonstrateFileHistory(repository);
        demonstratePrettyFormats(repository);
        demonstrateReflog(repository);
        demonstrateDiagnostic(repository);
        runValidation(repository);

        section("14. Final history");

        std::cout
            << gitText(
                   repository,
                   {
                       "log",
                       "--graph",
                       "--decorate",
                       "--oneline",
                       "--all"
                   }
               )
            << "\n";

        showStatus(repository);

        /*
         * The repository can now be removed because every demonstration has
         * already completed. The real lesson is the sequence of commands,
         * not persistence of this temporary repository.
         */
        fs::remove_all(temporaryDirectory, cleanupError);

        section("15. End of case study");
        std::cout
            << "All Git history demonstrations completed successfully.\n";

        return 0;
    }
    catch (const GitError& error) {
        std::cerr
            << "\nGit error:\n"
            << error.what()
            << "\n";

        return 1;
    }
    catch (const std::exception& error) {
        std::cerr
            << "\nUnexpected error:\n"
            << error.what()
            << "\n";

        return 1;
    }
}
