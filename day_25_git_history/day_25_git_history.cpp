/*
 * Git History: log, diff, show, reset, revert
 *
 * C++17 industry-style case study:
 * A repository maintenance audit tool.
 *
 * The program creates a temporary Git repository, builds a realistic
 * development history, and uses Git commands to inspect and reason about
 * that history.
 *
 * Demonstrated concepts:
 *   - commit history
 *   - repository state
 *   - git log
 *   - git show
 *   - git diff
 *   - git reset
 *   - git revert
 *   - branches and merges
 *   - revision expressions
 *   - reflog
 *   - file-specific history
 *   - validation
 *   - process execution
 *   - machine-readable output
 *   - complexity and operational trade-offs
 *
 * Requirements:
 *   - C++17 or later
 *   - Git executable available on PATH
 *
 * No external C++ libraries are required.
 */

